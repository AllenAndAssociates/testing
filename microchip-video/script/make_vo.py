"""Generate the Kokoro-82M voiceover with word-level timings.

Reads script/narration.json, synthesizes each chapter with Kokoro (PyTorch),
joins them with fixed gaps and writes:

  assets/vo/vo.wav          the voiceover (24 kHz mono, loudness-normalized later)
  assets/timing.js          window.VO = { duration, chapters[], words[] } for the compositions
  transcript.json           word-level transcript, same shape as the repo's original

Usage:  python script/make_vo.py   (run from the project root, inside a venv with kokoro>=0.9.4)
"""

import json
import re
from pathlib import Path

import numpy as np
import soundfile as sf
from kokoro import KPipeline

ROOT = Path(__file__).resolve().parent.parent
SR = 24000

cfg = json.loads((ROOT / "script" / "narration.json").read_text())
pipe = KPipeline(lang_code="a", repo_id="hexgrad/Kokoro-82M")

audio_parts = [np.zeros(int(cfg["lead_in"] * SR), dtype=np.float32)]
cursor = cfg["lead_in"]
chapters, words = [], []

for ch in cfg["chapters"]:
    ch_start = cursor
    ch_words = []
    for result in pipe(ch["text"], voice=cfg["voice"], speed=cfg["speed"], split_pattern=None):
        audio = result.audio.detach().cpu().numpy().astype(np.float32)
        for tok in result.tokens:
            text = tok.text
            if tok.start_ts is None or tok.end_ts is None or not re.search(r"[A-Za-z0-9]", text):
                # punctuation: attach to the previous word so captions read naturally
                if ch_words and text.strip():
                    ch_words[-1]["text"] += text
                continue
            ch_words.append(
                {
                    "text": text,
                    "start": round(cursor + float(tok.start_ts), 3),
                    "end": round(cursor + float(tok.end_ts), 3),
                    "ch": ch["id"],
                }
            )
        audio_parts.append(audio)
        cursor += len(audio) / SR
    ch_end = cursor
    chapters.append(
        {"id": ch["id"], "title": ch["title"], "start": round(ch_start, 3), "end": round(ch_end, 3)}
    )
    words.extend(ch_words)
    gap = cfg["gap_after_chapter"]
    audio_parts.append(np.zeros(int(gap * SR), dtype=np.float32))
    cursor += gap
    print(f"{ch['id']:>10}  {ch_start:7.2f} – {ch_end:7.2f}  ({ch_end - ch_start:5.2f}s, {len(ch_words)} words)")

audio_parts.append(np.zeros(int(cfg["tail"] * SR), dtype=np.float32))
cursor += cfg["tail"]
full = np.concatenate(audio_parts)
(ROOT / "assets" / "vo").mkdir(parents=True, exist_ok=True)
sf.write(ROOT / "assets" / "vo" / "vo_raw.wav", full, SR)

duration = round(len(full) / SR, 3)
vo = {"duration": duration, "chapters": chapters, "words": words}
(ROOT / "assets" / "timing.js").write_text(
    "/* generated by script/make_vo.py — do not edit by hand */\nwindow.VO = "
    + json.dumps(vo, separators=(",", ":"))
    + ";\n"
)
transcript = [
    {"id": f"w{i}", "text": w["text"], "start": w["start"], "end": w["end"]} for i, w in enumerate(words)
]
(ROOT / "transcript.json").write_text(json.dumps(transcript, indent=2) + "\n")
print(f"total {duration:.2f}s, {len(words)} words")
