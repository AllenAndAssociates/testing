// Writes index.html from the voiceover timings (assets/timing.js).
// Re-run after script/make_vo.py so every scene host lines up with the narration.
//   node script/build.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(join(ROOT, "assets/timing.js"), "utf8");
const VO = JSON.parse(src.slice(src.indexOf("=") + 1).trim().replace(/;$/, ""));
const f = (x) => (Math.round(x * 1000) / 1000).toString();

// same rule as World.slot in assets/js/core.js
function slot(i) {
  const c = VO.chapters[i];
  const prev = VO.chapters[i - 1];
  const next = VO.chapters[i + 1];
  return {
    start: prev ? (prev.end + c.start) / 2 : 0,
    end: next ? (c.end + next.start) / 2 : VO.duration,
  };
}

const D = VO.duration;
// optional music bed from script/make_music.py + script/loop_music.sh, kept ~12 dB under the voice
const music = existsSync(join(ROOT, "assets/music/bed.wav"))
  ? `      <audio
        id="music"
        class="clip"
        src="assets/music/bed.wav"
        data-start="0"
        data-duration="${f(D)}"
        data-track-index="6"
        data-timeline-role="music"
        data-volume="0.6"
      ></audio>
`
  : "";
const hosts = VO.chapters
  .map((c, i) => {
    const file = `compositions/ch-${c.id}.html`;
    if (!existsSync(join(ROOT, file))) return "";
    const s = slot(i);
    return `      <div
        id="ch-${c.id}"
        data-composition-id="ch-${c.id}"
        data-composition-src="${file}"
        data-start="${f(s.start)}"
        data-duration="${f(s.end - s.start)}"
        data-track-index="2"
        data-track-kind="graphics"
        data-width="1920"
        data-height="1080"
        style="z-index: 3"
      ></div>`;
  })
  .filter(Boolean)
  .join("\n");

const html = `<!doctype html>
<html
  lang="en"
  data-composition-variables='[
    {"id":"color-ground","type":"color","label":"Background","default":"#05070b"},
    {"id":"color-ink","type":"color","label":"Text","default":"#e9eef2"},
    {"id":"color-accent","type":"color","label":"Accent (copper)","default":"#e0894b"},
    {"id":"font-display","type":"string","label":"Display font","default":"Outfit"},
    {"id":"font-data","type":"string","label":"Data font","default":"IBM Plex Mono"}
  ]'
>
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <title>How Microchips Are Made</title>
    <!-- generated by script/build.mjs from assets/timing.js -->
    <script src="assets/lib/gsap.min.js"></script>
    <script src="assets/lib/three.min.js"></script>
    <script src="assets/timing.js"></script>
    <script src="assets/js/core.js"></script>
    <script src="assets/js/shots-hook.js"></script>
    <script src="assets/js/shots-build.js"></script>
    <script src="assets/js/shots-fab.js"></script>
    <script src="assets/js/shots-tools.js"></script>
    <script src="assets/js/shots-end.js"></script>
    <script src="assets/js/overlay-kit.js"></script>
    <link rel="stylesheet" href="assets/css/film.css" />
  </head>
  <body>
    <div
      id="root"
      data-composition-id="main"
      data-start="0"
      data-duration="${f(D)}"
      data-width="1920"
      data-height="1080"
    >
      <div id="ground" style="position: absolute; inset: 0; background: var(--color-ground); z-index: 0"></div>
      <div
        id="stage"
        data-composition-id="stage"
        data-composition-src="compositions/stage.html"
        data-start="0"
        data-duration="${f(D)}"
        data-track-index="1"
        data-track-kind="graphics"
        data-width="1920"
        data-height="1080"
        style="z-index: 1"
      ></div>
${hosts}
${music}      <audio
        id="vo"
        class="clip"
        src="assets/vo/vo.wav"
        data-start="0"
        data-duration="${f(D)}"
        data-track-index="5"
        data-volume="1"
      ></audio>
    </div>
    <script>
      const tl = gsap.timeline({ paused: true });
      tl.set({}, {}, ${f(D)});
      window.__timelines["main"] = tl;
    </script>
  </body>
</html>
`;
writeFileSync(join(ROOT, "index.html"), html);
console.log(`index.html: ${f(D)}s, ${hosts ? hosts.split("data-composition-src").length - 1 : 0} chapter overlays`);
